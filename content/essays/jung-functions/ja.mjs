<p>市場にあふれる商業化された性格診断（例えば16Personalitiesなど）と、ユング本来の八大認知機能理論は、本質的にまったく別の体系です。流行の4文字二分法アンケートは、実質的にはユング類型論の皮を被った「ビッグファイブ（Big Five）の簡略化テスト」にすぎません。商業組織は大衆心理に迎合し、被験者に心地よい自己肯定感を与えるため、各性格タイプが抱える影の側面や欠陥、神経症的弱点を意図的に削ぎ落としてきました。</p>
